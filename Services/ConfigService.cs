using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using BeamMPLauncher.Models;

namespace BeamMPLauncher.Services;

public class ConfigService
{
    private readonly string _configPath;

    public ConfigService(string configPath)
    {
        _configPath = configPath;
    }

    public ServerConfig LoadConfig()
    {
        var config = new ServerConfig();
        if (!File.Exists(_configPath))
        {
            Console.WriteLine($"Config file not found at: {_configPath}");
            return config;
        }

        try
        {
            var lines = File.ReadAllLines(_configPath);
            string currentSection = "";

            foreach (var line in lines)
            {
                string trimmed = line.Trim();
                if (string.IsNullOrWhiteSpace(trimmed) || trimmed.StartsWith("#")) continue;

                // Section detection
                if (trimmed.StartsWith("[") && trimmed.EndsWith("]"))
                {
                    currentSection = trimmed.Substring(1, trimmed.Length - 2);
                    continue;
                }

                // Key-Value parsing
                var parts = trimmed.Split(new[] { '=' }, 2);
                if (parts.Length != 2) continue;

                string key = parts[0].Trim();
                // Handle inline comments
                string rawValue = parts[1];
                if (rawValue.Contains("#"))
                {
                    rawValue = rawValue.Split('#')[0];
                }
                string value = rawValue.Trim().Trim('"'); 

                if (currentSection == "General")
                {
                    SetProperty(config.General, key, value);
                }
                else if (currentSection == "Misc")
                {
                    SetProperty(config.Misc, key, value);
                }
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error manually parsing config: {ex.Message}");
        }

        return config;
    }

    private void SetProperty(object target, string key, string value)
    {
        var prop = target.GetType().GetProperty(key);
        if (prop != null && prop.CanWrite)
        {
            try
            {
                if (prop.PropertyType == typeof(int))
                {
                    if (int.TryParse(value, out int iVal)) prop.SetValue(target, iVal);
                }
                else if (prop.PropertyType == typeof(bool))
                {
                    // TOML / C# bool string check
                    if (bool.TryParse(value, out bool bVal)) prop.SetValue(target, bVal);
                }
                else
                {
                    prop.SetValue(target, value);
                }
            }
            catch { }
        }
    }

    public void SaveConfig(ServerConfig config)
    {
        // Propagate exceptions to the caller (ViewModel) so they can be shown to the user
        var sb = new StringBuilder();

        // We will reconstruct the file to keep it simple and clean
        // Header
        sb.AppendLine("# BeamMP Server Launcher Configuration");
        sb.AppendLine("# Generated by Launcher");
        sb.AppendLine();

        // General Section
        sb.AppendLine("[General]");
        WriteProperties(sb, config.General);

        sb.AppendLine();

        // Misc Section
        sb.AppendLine("[Misc]");
        WriteProperties(sb, config.Misc);

        File.WriteAllText(_configPath, sb.ToString(), Encoding.UTF8);
    }

    private void WriteProperties(StringBuilder sb, object obj)
    {
        foreach (var prop in obj.GetType().GetProperties())
        {
            // Skip ReactiveUI infrastructure properties
            if (prop.Name == "Changing" || prop.Name == "Changed" || prop.Name == "ThrownExceptions") continue;

            var val = prop.GetValue(obj);
            string writeVal = val?.ToString() ?? "";

            if (prop.PropertyType == typeof(string))
            {
                // Strings need quotes in TOML
                sb.AppendLine($"{prop.Name} = \"{writeVal}\"");
            }
            else if (prop.PropertyType == typeof(bool))
            {
                // Lowercase bools
                sb.AppendLine($"{prop.Name} = {writeVal.ToLower()}");
            }
            else
            {
                sb.AppendLine($"{prop.Name} = {writeVal}");
            }
        }
    }
}
